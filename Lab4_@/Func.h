
#pragma once
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

/**
 * @brief Виділяє динамічну пам'ять для двовимірної матриці.
 *
 * @param rows Кількість рядків матриці.
 * @param cols Кількість стовпців матриці.
 *
 * @return int** Вказівник на створений двовимірний динамічний масив.
 *               @note Пам'ять має бути звільнена за допомогою функції free_matrix().
 */
int** allocate_matrix(int rows, int cols);

/**
 * @brief Звільняє динамічну пам'ять, виділену під двовимірну матрицю.
 *
 * @param matrix Вказівник на двовимірну матрицю.
 * @param rows Кількість рядків матриці.
 *
 * @return void
 */
void free_matrix(int** matrix, int rows);

/**
 * @brief Виводить двовимірну матрицю у консоль у вигляді таблиці.
 *
 * @param matrix Вказівник на матрицю для виведення.
 * @param rows Кількість рядків.
 * @param cols Кількість стовпців.
 * @param name Назва матриці для заголовка (наприклад, "A", "B", "C").
 *
 * @return void
 */
void print_matrix(int** matrix, int rows, int cols, const char* name);

/**
 * @brief Заповнює елементи матриці обраним користувачем способом.
 *
 * Надає вибір: ручне введення, генератор випадкових чисел,
 * формула за індексами або рекурентна формула.
 *
 * @param matrix Вказівник на матрицю для заповнення.
 * @param rows Кількість рядків.
 * @param cols Кількість стовпців.
 * @param name Назва матриці.
 *
 * @return void
 */
void fill_matrix(int** matrix, int rows, int cols, const char* name);

/**
 * @brief Знаходить максимальний та мінімальний елементи вище головної діагоналі (Варіант 21).
 *
 * Перебирає лише елементи з індексами j > i у квадратній матриці A.
 *
 * @param A Вказівник на квадратну матрицю A.
 * @param n_a Розмірність квадратної матриці A (n_a x n_a).
 * @param max_a Вказівник на змінну для збереження максимального значення.
 * @param min_a Вказівник на змінну для збереження мінімального значення.
 *
 * @return void (результати повертаються через вказівники max_a та min_a)
 */
void max_min(int** A, int n_a, int* max_a, int* min_a);

/**
 * @brief Створює та повертає нову транспоновану матрицю B^T.
 *
 * @param B Вказівник на початкову прямокутну матрицю B.
 * @param n_b Кількість рядків початкової матриці B.
 * @param m_b Кількість стовпців початкової матриці B.
 *
 * @return int** Вказівник на нову динамічну матрицю розміром (m_b x n_b).
 *               @note Вимагає подальшого звільнення пам'яті через free_matrix().
 */
int** transpose_b(int** B, int n_b, int m_b);

/**
 * @brief Обчислює матричний добуток C = A x B.
 *
 * @param B Вказівник на матрицю B (розмір n_b x m_b).
 * @param n_b Кількість рядків матриці B.
 * @param m_b Кількість стовпців матриці B.
 * @param A Вказівник на квадратну матрицю A (розмір n_a x n_a).
 * @param n_a Розмірність квадратної матриці A.
 *
 * @return int** Вказівник на результуючу динамічну матрицю C (розмір n_a x m_b),
 *               або NULL у разі невідповідності розмірностей.
 *               @note Вимагає подальшого звільнення пам'яті через free_matrix().
 */
int** mult_a_b(int** B, int n_b, int m_b, int** A, int n_a);

/**
 * @brief Сортує елементи матриці A за зростанням.
 *
 * @param A Вказівник на квадратну матрицю A.
 * @param n_a Розмірність матриці A.
 * @param row_index Індекс конкретного рядка для сортування (0..n_a-1),
 *                  або -1 для сортування усіх елементів всієї матриці A.
 *
 * @return void (сортування виконується безпосередньо у переданій матриці)
 */
void sort_matrix_a(int** A, int n_a, int row_index);

/**
 * @brief Обчислює та виводить суми елементів для кожного рядка A та кожного стовпця B.
 *
 * @param A Вказівник на матрицю A.
 * @param n_a Розмірність матриці A.
 * @param B Вказівник на матрицю B.
 * @param n_b Кількість рядків матриці B.
 * @param m_b Кількість стовпців матриці B.
 *
 * @return void
 */
void print_sums(int** A, int n_a, int** B, int n_b, int m_b);